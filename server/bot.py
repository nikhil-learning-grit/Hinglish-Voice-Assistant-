"""Midnight-Phantom-Hotline-Project - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

Required AI services:
- Sarvam (Speech-to-Text)
- Groq (LLM)
- Sarvam (Text-to-Speech)

Run the bot using::

    uv run bot.py
"""

import os
import sys
from pathlib import Path

from dotenv import load_dotenv
from loguru import logger
from pipecat.audio.vad.silero import SileroVADAnalyzer
from pipecat.frames.frames import LLMRunFrame
from pipecat.pipeline.pipeline import Pipeline
from pipecat.pipeline.worker import PipelineParams, PipelineWorker
from pipecat.processors.aggregators.llm_context import LLMContext
from pipecat.processors.aggregators.llm_response_universal import (
    LLMContextAggregatorPair,
    LLMUserAggregatorParams,
)
from pipecat.runner.types import RunnerArguments
from pipecat.runner.utils import create_transport
from pipecat.services.groq.llm import GroqLLMService
from pipecat.services.llm_service import FunctionCallParams
from pipecat.services.sarvam.stt import SarvamSTTService
from pipecat.services.sarvam.tts import SarvamTTSService
from pipecat.transports.base_transport import BaseTransport, TransportParams
from pipecat.workers.runner import WorkerRunner

load_dotenv(override=True)

# The hospital data and business logic live at the repository root.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from hospital_tools import (  # noqa: E402
    book_appointment,
    get_available_slots,
    get_hospital_information,
)


def _required_env(name: str) -> str:
    value = os.getenv(name)
    if not value:
        raise RuntimeError(f"Missing required environment variable: {name}")
    return value


async def hospital_information(params: FunctionCallParams, topic: str):
    """Look up verified hospital information such as departments, timings, location, or FAQs.

    Args:
        topic: The user's question or a topic such as departments, timings, contact, or policies.
    """
    await params.result_callback(get_hospital_information(topic))


async def available_appointment_slots(
    params: FunctionCallParams, specialization: str, date: str
):
    """Check real appointment availability for a department and date (YYYY-MM-DD).

    Args:
        specialization: Exact hospital department or doctor specialization.
        date: Appointment date in YYYY-MM-DD format.
    """
    await params.result_callback(get_available_slots(specialization, date))


async def make_appointment(
    params: FunctionCallParams, patient_name: str, specialization: str, date: str, time_slot: str
):
    """Book a slot after the patient has provided all four required details and availability was checked.

    Args:
        patient_name: Patient's full name.
        specialization: Hospital department or specialization.
        date: Appointment date in YYYY-MM-DD format.
        time_slot: Available time exactly as returned by the availability lookup.
    """
    await params.result_callback(
        book_appointment(patient_name, specialization, date, time_slot)
    )


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session.

    Args:
        transport: The transport for this session, built by ``create_transport``
            (or by hand for the dial-out/SIP production flows).
        runner_args: Runner session arguments. Carries the request ``body``
            (e.g. dial-out settings, SIP call details) and ``session_id``; the
            standard web/telephony pipelines don't need it.
    """
    logger.info("Starting bot")

    # Speech-to-Text service
    sarvam_api_key = _required_env("SARVAM_API_KEY")
    groq_api_key = _required_env("GROQ_API_KEY")
    groq_model = _required_env("GROQ_MODEL")
    sarvam_voice_id = _required_env("SARVAM_VOICE_ID")

    stt = SarvamSTTService(api_key=sarvam_api_key)

    # Text-to-Speech service
    tts = SarvamTTSService(
        api_key=sarvam_api_key,
        settings=SarvamTTSService.Settings(
            voice=sarvam_voice_id,
        ),
    )

    # LLM service
    llm = GroqLLMService(
        api_key=groq_api_key,
        settings=GroqLLMService.Settings(
            model=groq_model,
            system_instruction=(
                "You are a hospital receptionist. Speak naturally and concisely in English, Hindi, "
                "or Hinglish, matching the caller. Your responses will be spoken aloud, so avoid "
                "formatting. Use hospital tools for all hospital facts and availability; never "
                "invent them. For booking, ask for any missing patient name, specialization, date, "
                "or time before calling the booking tool. Check availability first and use an exact "
                "returned slot. Confirm a booking only when the booking tool returns success; "
                "otherwise explain the real failure and offer to check alternatives."
            ),
        ),
    )

    context = LLMContext(
        tools=[hospital_information, available_appointment_slots, make_appointment]
    )
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(vad_analyzer=SileroVADAnalyzer()),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    runner = WorkerRunner(handle_sigint=runner_args.handle_sigint)

    await runner.add_workers(worker)

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation
        context.add_message(
            {"role": "developer", "content": "Start by concisely introducing yourself."}
        )
        await worker.queue_frames([LLMRunFrame()])

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await runner.cancel()

    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport_params = {
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)

    await run_bot(transport, runner_args)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()
